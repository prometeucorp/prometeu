/// A fresh branch name that `taken` (local and remote branch names) does not contain. `random`
/// supplies the entropy, so tests can be deterministic.
pub fn fresh_branch(taken: &[String], mut random: impl FnMut() -> u64) -> String {
    let has = |name: &str| {
        taken
            .iter()
            .any(|b| b == name || b.ends_with(&format!("/{name}")))
    };
    let mut base = String::new();
    for _ in 0..20 {
        let noun = NOUNS[(random() % NOUNS.len() as u64) as usize];
        let adjective = ADJECTIVES[(random() % ADJECTIVES.len() as u64) as usize];
        base = format!("prometeu/{noun}-{adjective}-{:04}", random() % 10_000);
        if !has(&base) {
            return base;
        }
    }
    (2..)
        .map(|n| format!("{base}-{n}"))
        .find(|candidate| !has(candidate))
        .unwrap_or(base)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_follow_the_desktop_convention() {
        let name = fresh_branch(&[], || 7);
        assert_eq!(name, "prometeu/cedro-novo-0007");
    }

    #[test]
    fn taken_names_are_skipped_then_suffixed() {
        let taken = vec!["origin/prometeu/cedro-novo-0007".to_string()];
        assert_eq!(fresh_branch(&taken, || 7), "prometeu/cedro-novo-0007-2");
    }
}
